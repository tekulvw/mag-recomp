"""The launcher's update check (src/player_update.cpp): its synthetic core tests, and the platform
HTTPS transport against a fake release server on 127.0.0.1 (tests/fake_release_server.py).

All inputs are synthetic: releases, checksums and archives are made up here, and every signature
is made with a throwaway key generated by the test. No real signing key is used anywhere.
"""
import json
import os
import pathlib
import shutil
import subprocess
import sys
import tempfile
import unittest

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from fake_release_server import FakeReleaseServer  # noqa: E402

CXX = shutil.which('c++') or shutil.which('clang++') or shutil.which('g++')
CC = shutil.which('cc') or shutil.which('clang') or shutil.which('gcc')
MONOCYPHER = ['src/third_party/monocypher/monocypher.c', 'src/third_party/monocypher/monocypher-ed25519.c']
CORE = ['tests/player_update.cpp', 'src/player_update.cpp', 'src/player_portal.cpp', 'src/player_sha256.cpp']
REVISION = '0123456789abcdef0123456789abcdef01234567'
SEED, KEY_ID = '5eed', '0102030405060708'


def transport():
    """This host's portal transport sources and link flags, or None."""
    if sys.platform == 'darwin':
        return ['src/player_portal_macos.mm'], ['-fobjc-arc', '-framework', 'Foundation', '-framework', 'AppKit']
    if sys.platform.startswith('linux') and pathlib.Path('/usr/include/openssl/ssl.h').is_file():
        return ['src/player_portal_openssl.cpp'], ['-lssl', '-lcrypto']
    if os.name == 'nt':
        return ['src/player_portal_winhttp.cpp'], ['-lwinhttp']
    return None


@unittest.skipUnless(CXX and CC and transport(), 'C and C++ compilers and a platform HTTPS transport')
class UpdateCheckTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.TemporaryDirectory(prefix='mag-update-')
        cls.addClassCleanup(cls.tmp.cleanup)
        cls.root = pathlib.Path(cls.tmp.name)
        objects = []
        # Monocypher is C; the packaged binaries compile it as C too.
        for source in MONOCYPHER:
            target = cls.root / (pathlib.Path(source).stem + ('.obj' if os.name == 'nt' else '.o'))
            subprocess.run([CC, '-O1', '-c', str(ROOT / source), '-o', str(target)], check=True, timeout=300)
            objects.append(str(target))
        sources, flags = transport()
        cls.binary = cls.root / ('player_update.exe' if os.name == 'nt' else 'player_update')
        build = subprocess.run([CXX, '-std=c++17', '-Wall', '-Wextra', '-Werror', '-I' + str(ROOT / 'src'),
                                *(['-D_CRT_SECURE_NO_WARNINGS'] if os.name == 'nt' else []),
                                *[str(ROOT / s) for s in CORE + sources], *objects, *flags,
                                *([] if os.name == 'nt' else ['-pthread']), '-o', str(cls.binary)],
                               capture_output=True, text=True, timeout=600)
        if build.returncode:
            raise AssertionError(build.stderr)

    def run_binary(self, *args, check=True):
        result = subprocess.run([str(self.binary), *map(str, args)], capture_output=True, text=True, timeout=120)
        if check:
            self.assertEqual(result.returncode, 0, result.stderr)
        return result

    def test_core(self):
        scratch = self.root / 'scratch'
        scratch.mkdir()
        result = self.run_binary(scratch)
        self.assertIn('update checks passed', result.stdout)

    # ---- the platform transport against the fake release server ----
    def signed(self, sums, tag, seed=SEED, key_id=KEY_ID, legacy=False):
        path = self.root / f'sums-{tag}-{seed}.txt'
        path.write_bytes(sums)
        comment = f'mag-recomp release {tag} source {REVISION}'
        return self.run_binary('sign', seed, key_id, path, comment, *(['legacy'] if legacy else [])).stdout.encode()

    def key_line(self, seed=SEED, key_id=KEY_ID):
        return self.run_binary('pubkey', seed, key_id).stdout.strip()

    def release(self, tag='v0.16.0', **signing):
        archive = b'synthetic installer archive ' + tag.encode()
        import hashlib
        sums = (f'{hashlib.sha256(archive).hexdigest()}  mag-installer-{tag}-windows-x86_64.zip\n'
                f'{"b" * 64}  mag-installer-{tag}-linux-x86_64.tar.gz\n').encode()
        return FakeReleaseServer(tag, sums, self.signed(sums, tag, **signing), archive)

    def config(self, server, version='0.15.1', keys=None):
        return json.dumps({'repository': 'tekulvw/mag-recomp', 'platform': 'windows-x86_64', 'version': version,
                           'api': server.api, 'channel': 'test', 'keys': keys or [self.key_line()]})

    def check(self, server, state, forced=True, **config):
        result = self.run_binary('live', self.config(server, **config), state, *(['forced'] if forced else []))
        outcome, message = (result.stdout.splitlines() + ['', ''])[:2]
        return outcome, message, json.loads(state.read_text()) if state.exists() else {}

    def test_newer_signed_release_over_the_platform_transport(self):
        with self.release() as server:
            state = self.root / 'newer.json'
            outcome, message, saved = self.check(server, state)
            self.assertEqual(outcome, 'available', message)
            self.assertEqual((saved['tag'], saved['status'], saved['etag'], saved['source_revision']),
                             ('v0.16.0', 'available', '"fake-1"', REVISION))
            latest = server.latest_requests()[-1][2]
            self.assertEqual(latest.get('Accept'), 'application/vnd.github+json')
            self.assertEqual(latest.get('X-GitHub-Api-Version'), '2022-11-28')
            self.assertEqual(latest.get('User-Agent'), 'MAG-launcher')
            # The small files came through the redirect hop.
            self.assertTrue(any(r[1].startswith('/assets/SHA256SUMS.txt.minisig?sig=') for r in server.requests))
            # Unchanged: a conditional request and a 304, and the offer stays.
            outcome, message, saved = self.check(server, state, forced=False)
            self.assertEqual(outcome, 'not-due')
            saved['next_check'] = 0
            state.write_text(json.dumps(saved))
            outcome, message, saved = self.check(server, state, forced=False)
            self.assertEqual(outcome, 'available', message)
            self.assertIn('304', message)
            self.assertEqual(server.latest_requests()[-1][2].get('If-None-Match'), '"fake-1"')

    def test_nothing_newer_or_nothing_published(self):
        with self.release(tag='v0.15.1') as server:
            outcome, _, saved = self.check(server, self.root / 'same.json')
            self.assertEqual((outcome, saved['status']), ('up-to-date', 'up_to_date'))
        with self.release() as server:
            server.mode = 'none'
            outcome, _, _ = self.check(server, self.root / 'none.json')
            self.assertEqual(outcome, 'up-to-date')

    def test_never_offered(self):
        cases = {
            'prerelease': 'failed', 'draft': 'failed', 'unsigned': 'up-to-date', 'truncated': 'failed',
            'redirect-away': 'failed', 'malformed': 'failed',
        }
        for mode, expected in cases.items():
            with self.subTest(mode=mode), self.release() as server:
                server.mode = mode
                state = self.root / f'{mode}.json'
                outcome, message, saved = self.check(server, state)
                self.assertEqual(outcome, expected, message)
                self.assertNotEqual(saved.get('status'), 'available')
        # Signed by a key this MAG does not trust, signed in the legacy form, or for another tag.
        with self.release(seed='bad', key_id='0909090909090909') as server:
            outcome, message, _ = self.check(server, self.root / 'stranger.json')
            self.assertEqual(outcome, 'failed')
            self.assertIn('0909090909090909 is not trusted', message)
        with self.release(legacy=True) as server:
            outcome, message, _ = self.check(server, self.root / 'legacy.json')
            self.assertEqual(outcome, 'failed')
            self.assertIn('legacy', message)
        with self.release() as server:
            server.signature = self.signed(server.sums, 'v0.15.9')
            outcome, message, _ = self.check(server, self.root / 'replay.json')
            self.assertEqual(outcome, 'failed')
            self.assertIn('another release', message)

    def test_rate_limits(self):
        with self.release() as server:
            server.mode = 'rate-limited'
            state = self.root / 'limited.json'
            outcome, _, saved = self.check(server, state)
            self.assertEqual(outcome, 'rate-limited')
            self.assertGreater(saved['blocked_until'], saved['last_check'])
            # Blocked: Check now does not ask again until the reset.
            before = len(server.latest_requests())
            outcome, _, _ = self.check(server, state)
            self.assertEqual((outcome, len(server.latest_requests())), ('not-due', before))
            server.mode = 'retry-after'
            outcome, _, saved = self.check(server, self.root / 'retry.json')
            self.assertEqual(outcome, 'rate-limited')
            self.assertEqual(saved['blocked_until'] - saved['last_check'], 120)

    def test_offline_is_silent(self):
        server = self.release().start()
        api = server.api
        server.stop()
        state = self.root / 'offline.json'
        config = json.dumps({'repository': 'tekulvw/mag-recomp', 'platform': 'windows-x86_64', 'version': '0.15.1',
                             'api': api, 'channel': 'test', 'keys': [self.key_line()]})
        result = self.run_binary('live', config, state, 'forced')
        self.assertEqual(result.stdout.splitlines()[0], 'failed')
        self.assertEqual(json.loads(state.read_text())['status'], 'failed')

    def test_a_test_channel_must_stay_on_this_computer(self):
        config = json.dumps({'repository': 'tekulvw/mag-recomp', 'platform': 'windows-x86_64', 'version': '0.15.1',
                             'api': 'http://example.invalid', 'channel': 'test', 'keys': [self.key_line()]})
        result = self.run_binary('live', config, self.root / 'x.json', check=False)
        self.assertEqual(result.returncode, 2)
        self.assertIn('not GitHub', result.stderr)


if __name__ == '__main__':
    unittest.main()
