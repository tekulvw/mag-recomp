// C-compatible synchronous views. Owned packet copies never retain these pointers.
use crate::TextureLayout as NativeTextureLayout;
use crate::packet as raw;
use crate::*;
use core::mem::{align_of, offset_of, size_of};
#[repr(C)]
#[derive(Clone, Copy)]
pub struct TextureSlot {
    pub slot: u32,
    pub dimension: u32,
    pub sample_kind: u32,
    pub arrayed: u32,
    pub multisampled: u32,
    pub reserved: u32,
}
#[repr(C)]
#[derive(Clone, Copy)]
pub struct SamplerSlot {
    pub slot: u32,
    pub comparison: u32,
}
#[repr(C)]
#[derive(Clone, Copy)]
pub struct Program {
    pub stage: u32,
    pub reserved: u32,
    pub shader: ShaderStage,
    pub buffers: *const BindingLayout,
    pub buffer_count: u32,
    pub texture_count: u32,
    pub textures: *const TextureSlot,
    pub samplers: *const SamplerSlot,
    pub sampler_count: u32,
    pub vertex_location_count: u32,
    pub vertex_locations: *const u32,
    pub threads: [u32; 3],
    pub reserved1: u32,
}
#[repr(C)]
#[derive(Clone, Copy)]
pub struct StencilFace {
    pub compare: u32,
    pub fail: u32,
    pub depth_fail: u32,
    pub pass: u32,
    pub reference: u32,
    pub read_mask: u32,
    pub write_mask: u32,
    pub reserved: u32,
}
#[repr(C)]
#[derive(Clone, Copy)]
pub struct RasterState {
    pub known_fields: u64,
    pub unresolved_obligations: u64,
    pub cull_mode: u32,
    pub front_face: u32,
    pub depth_enabled: u32,
    pub depth_compare: u32,
    pub depth_write: u32,
    pub blend_enabled: u32,
    pub src_rgb: u32,
    pub dst_rgb: u32,
    pub rgb_equation: u32,
    pub src_alpha: u32,
    pub dst_alpha: u32,
    pub alpha_equation: u32,
    pub color_write_mask: u32,
    pub stencil_enabled: u32,
    pub blend_constant: [f32; 4],
    pub front_stencil: StencilFace,
    pub back_stencil: StencilFace,
    pub depth_bounds_enabled: u32,
    pub bias_enabled: u32,
    pub topology: u32,
    pub samples: u32,
    pub depth_bounds_min: f32,
    pub depth_bounds_max: f32,
    pub bias_constant: f32,
    pub bias_slope: f32,
    pub bias_clamp: f32,
    pub reserved: u32,
}
#[repr(C)]
#[derive(Clone, Copy)]
pub struct Pipeline {
    pub vertex_program: u32,
    pub fragment_program: u32,
    pub vertex_stride: u32,
    pub attribute_count: u32,
    pub attributes: *const VertexAttribute,
    pub color_format: u32,
    pub depth_format: u32,
    pub binding_model: u32,
    pub reserved: u32,
    pub textures: *const NativeTextureLayout,
    pub texture_count: u32,
    pub reserved1: u32,
    pub state: RasterState,
}
#[repr(C)]
#[derive(Clone, Copy)]
pub struct Buffer {
    pub role: u32,
    pub reserved: u32,
    pub bytes: *const std::ffi::c_void,
    pub length: u64,
}
#[repr(C)]
#[derive(Clone, Copy)]
pub struct Subresource {
    pub mip: u32,
    pub layer: u32,
    pub width: u32,
    pub height: u32,
    pub depth: u32,
    pub row_bytes: u32,
    pub bytes: *const std::ffi::c_void,
    pub length: u64,
}
#[repr(C)]
#[derive(Clone, Copy)]
pub struct Image {
    pub format: u32,
    pub dimension: u32,
    pub width: u32,
    pub height: u32,
    pub depth: u32,
    pub layers: u32,
    pub mip_count: u32,
    pub samples: u32,
    pub subresources: *const Subresource,
    pub subresource_count: u32,
    pub reserved: u32,
}
#[repr(C)]
#[derive(Clone, Copy)]
pub struct ImageView {
    pub image: u32,
    pub base_mip: u32,
    pub mip_count: u32,
    pub base_layer: u32,
    pub layer_count: u32,
    pub remap: [u32; 4],
    pub reserved: u32,
}
#[repr(C)]
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Sampler {
    pub known_fields: u64,
    pub min_filter: u32,
    pub mag_filter: u32,
    pub mip_filter: u32,
    pub wrap_s: u32,
    pub wrap_t: u32,
    pub wrap_r: u32,
    pub comparison_enabled: u32,
    pub comparison: u32,
    pub lod_min: f32,
    pub lod_max: f32,
    pub lod_bias: f32,
    pub max_anisotropy: f32,
    pub border: [f32; 4],
}
#[repr(C)]
#[derive(Clone, Copy)]
pub struct BufferUse {
    pub buffer: u32,
    pub reserved: u32,
    pub offset: u64,
    pub length: u64,
}
#[repr(C)]
#[derive(Clone, Copy)]
pub struct Binding {
    pub stage: u32,
    pub slot: u32,
    pub view: BufferUse,
}
#[repr(C)]
#[derive(Clone, Copy)]
pub struct TextureUse {
    pub stage: u32,
    pub texture_slot: u32,
    pub sampler_slot: u32,
    pub view: u32,
    pub sampler: u32,
    pub reserved: u32,
}
#[repr(C)]
#[derive(Clone, Copy)]
pub struct Draw {
    pub source_item: u64,
    pub source_partition: u64,
    pub unresolved_obligations: u64,
    pub pipeline: u32,
    pub index_count: u32,
    pub vertices: BufferUse,
    pub indices: BufferUse,
    pub buffers: *const Binding,
    pub buffer_count: u32,
    pub texture_count: u32,
    pub textures: *const TextureUse,
}
#[repr(C)]
#[derive(Clone, Copy)]
pub struct Dispatch {
    pub program: u32,
    pub binding_count: u32,
    pub bindings: *const Binding,
    pub groups: [u32; 3],
    pub reserved: u32,
}
#[repr(C)]
#[derive(Clone, Copy)]
pub struct Pass {
    pub source: Source,
    pub color: Attachment,
    pub depth: Attachment,
    pub draws: *const Draw,
    pub draw_count: u32,
    pub reserved: u32,
}
#[repr(C)]
#[derive(Clone, Copy)]
pub struct Item {
    pub pass: u32,
    pub reserved: u32,
    pub source_item: u64,
    pub unresolved_obligations: u64,
}
#[repr(C)]
#[derive(Clone, Copy)]
pub struct Desc {
    pub abi_version: u32,
    pub struct_size: u32,
    pub flags: u32,
    pub reserved: u32,
    pub source: Source,
    pub intended_items: u64,
    pub programs: *const Program,
    pub program_count: u32,
    pub pipeline_count: u32,
    pub pipelines: *const Pipeline,
    pub buffers: *const Buffer,
    pub buffer_count: u32,
    pub image_count: u32,
    pub images: *const Image,
    pub views: *const ImageView,
    pub view_count: u32,
    pub sampler_count: u32,
    pub samplers: *const Sampler,
    pub dispatches: *const Dispatch,
    pub dispatch_count: u32,
    pub pass_count: u32,
    pub passes: *const Pass,
    pub items: *const Item,
    pub item_count: u32,
    pub output_image: u32,
    pub target: *const HostImage,
    pub frame: *const HostFrame,
}
