"""Refuse tracked content that must never be published: game files, anything derived from them,
and machine-specific details. Runs over `git ls-files`; exits 1 and lists every finding."""
import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
# This checker and its test necessarily spell out the patterns they look for.
SELF = {'tools/check_public_tree.py', 'tests/test_check_public_tree.py'}
MAX_BYTES = 1_000_000
GAME_SUFFIXES = {'.bin', '.self', '.sprx', '.prx', '.elf', '.pkg', '.psarc', '.sdat', '.edat',
                 '.rap', '.iso', '.pup', '.o', '.a', '.dylib', '.so', '.ppm', '.png', '.wav'}
CONTENT = [
    ('absolute user path', re.compile(rb'/Users/[A-Za-z]|/home/[a-z]|/private/(tmp|var)/|~/Documents')),
    ('chat or session id', re.compile(rb'01a1[0-9a-f]{4}-[0-9a-f]{4}-7[0-9a-f]{3}-|claude\.ai/code/session|chatgpt\.com/')),
    ('email address', re.compile(rb'[A-Za-z0-9._%+-]+@(gmail|icloud|me|outlook|hotmail)\.com')),
    ('generated-code header', re.compile(rb'Auto-generated by (ppu|spu)_lifter')),
    ('embedded byte image', re.compile(rb'(?:0x[0-9a-fA-F]{2}\s*,\s*){64}')),
    ('base64 blob', re.compile(rb'[A-Za-z0-9+/]{200,}={0,2}')),
    ('disassembly listing', re.compile(rb'(?m)(?:^\s*(?:0x)?[0-9a-fA-F]{5,8}:?\s+(?:[0-9a-fA-F]{8}\s+)?'
                                       rb'(?:lwz|stw|addi|bl|mflr|stwu|lqd|stqd|shufb|brsl|ori|rlwinm)\b.*\n){5}')),
]


def tracked(root):
    out = subprocess.run(['git', '-C', str(root), 'ls-files', '-z'], check=True, capture_output=True).stdout
    return [p for p in out.decode().split('\0') if p]


def findings(root, paths):
    for path in paths:
        if path in SELF:
            continue
        file = root / path
        if not file.is_file():
            continue
        data = file.read_bytes()
        if Path(path).suffix.lower() in GAME_SUFFIXES:
            yield path, f'forbidden file type {Path(path).suffix}'
        if len(data) > MAX_BYTES:
            yield path, f'larger than {MAX_BYTES} bytes'
        if b'\0' in data:
            yield path, 'binary content'
            continue
        try:
            data.decode('utf-8')
        except UnicodeDecodeError:
            yield path, 'not UTF-8 text'
        for name, pattern in CONTENT:
            if pattern.search(data):
                yield path, name


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--root', type=Path, default=ROOT)
    args = parser.parse_args()
    problems = list(findings(args.root, tracked(args.root)))
    for path, reason in problems:
        print(f'{path}: {reason}')
    print(f'{len(problems)} finding(s)' if problems else 'public tree check passed')
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
